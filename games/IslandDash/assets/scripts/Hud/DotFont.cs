    /// <summary>Horizontal runs of lit pixels: (column, row, length), row 0 at the top.</summary>
    public static IEnumerable<(int Column, int Row, int Length)> Runs(string text)
    {
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            if (!Glyphs.TryGetValue(c, out var rows) && !Glyphs.TryGetValue(char.ToUpperInvariant(c), out rows))
                continue;

            for (var row = 0; row < Height; row++)
            {
                var bits = rows[row];
                var column = 0;
                while (column < Width)
                {
                    if (bits[column] != '1')
                    {
                        column++;
                        continue;
                    }

                    var start = column;
                    while (column < Width && bits[column] == '1')
                        column++;
                    yield return (i * Advance + start, row, column - start);
                }
            }
        }
    }

    public static int TextWidth(string text) => text.Length == 0 ? 0 : text.Length * Advance - 1;
